-- SportyFanz staff authentication recovery.
-- REVIEW BEFORE EXECUTION.
-- Back up the database before applying to production.
-- Existing staff accounts and passwords are preserved.

BEGIN;

-- Support revocation of previously issued admin sessions.
ALTER TABLE public.admin_users
  ADD COLUMN IF NOT EXISTS "sessionVersion" INTEGER NOT NULL DEFAULT 0;

-- Store one-time staff invitation and password-reset tokens.
CREATE TABLE IF NOT EXISTS public.admin_password_reset_tokens (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "adminUserId" INTEGER NOT NULL,
  "tokenHash" TEXT NOT NULL UNIQUE,
  purpose TEXT NOT NULL,
  "expiresAt" TIMESTAMPTZ NOT NULL,
  "usedAt" TIMESTAMPTZ,
  "createdAt" TIMESTAMPTZ NOT NULL DEFAULT NOW(),

  CONSTRAINT admin_password_reset_tokens_purpose_check
    CHECK (purpose IN ('INVITATION', 'PASSWORD_RESET')),

  CONSTRAINT admin_password_reset_tokens_admin_fkey
    FOREIGN KEY ("adminUserId")
    REFERENCES public.admin_users(id)
    ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS
  admin_password_reset_tokens_admin_idx
ON public.admin_password_reset_tokens ("adminUserId");

CREATE INDEX IF NOT EXISTS
  admin_password_reset_tokens_expires_idx
ON public.admin_password_reset_tokens ("expiresAt");

COMMIT;
